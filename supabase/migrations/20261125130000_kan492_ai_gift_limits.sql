-- KAN-492 — AI gift suggestions: new generation limits.
--
-- Founder decision 2026-11-25 (chat), replacing the KAN-489 limits
-- (spec v0.8 §03 "up to 5 generations per profile-edit session" + a rolling
-- 20 per 24 hours):
--   * up to 10 generations per editing session, and
--   * up to 30 generations per member in any rolling 30 days.
-- The 10-second cooldown stays (not shown to members).
--
-- Only claim_ai_gift_generation changes. Same signature, same SECURITY
-- DEFINER + pinned search_path, same profile row lock, same suspended-account
-- refusal, same consent-version recording, same grants (KAN-489 header has
-- the full threat model). The refusal reason 'daily_limit' becomes
-- 'monthly_limit' and the success payload's 'daily_remaining' becomes
-- 'monthly_remaining' (the app is updated in the same change).
--
-- Session ids are generated by the browser, so the 30-per-30-days cap is the
-- real bound on paid model calls: at most 30 per member per 30 days. Raising
-- the session cap from 5 to 10 does not raise that bound.
--
-- The claim log index ai_gift_generations_profile_created_idx
-- (profile_id, created_at desc) already serves the 30-day count.
--
-- Rollback (manual): re-run section 2 of
-- 20261123120000_kan489_ai_gift_generations.sql (the 5 / 20-per-24h version)
-- and redeploy the previous app build.
--
-- Dry-run probe (dev, as a member in a transaction, then ROLLBACK):
--   select public.claim_ai_gift_generation(gen_random_uuid(), 'v1-2026-11-23');
--   -- expect ok=true, session_remaining=9, monthly_remaining=29 for a member
--   -- with no claims in the last 30 days.

create or replace function public.claim_ai_gift_generation(p_session uuid, p_consent_version text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_session_cap constant integer := 10;
  v_window_cap  constant integer := 30;
  v_pid       uuid;
  v_suspended boolean;
  v_session   integer;
  v_window    integer;
  v_last      timestamptz;
  v_id        uuid;
begin
  if p_session is null then
    raise exception 'A session id is required' using errcode = '22004';
  end if;
  if p_consent_version is null or btrim(p_consent_version) = '' or char_length(p_consent_version) > 64 then
    raise exception 'A consent version is required' using errcode = '22004';
  end if;

  -- The caller's own profile, locked: concurrent claims run one at a time.
  select p.id, coalesce(p.is_suspended, false) into v_pid, v_suspended
    from public.profiles p
   where p.user_id = auth.uid()
     for update;
  if not found then
    raise exception 'Profile not found' using errcode = '42501';
  end if;
  -- A suspended account spends nothing (SEC-57 stance: no new paid work).
  if v_suspended then
    return jsonb_build_object('ok', false, 'reason', 'suspended');
  end if;

  select count(*) into v_session
    from public.ai_gift_generations g
   where g.profile_id = v_pid
     and g.session_id = p_session;
  if v_session >= v_session_cap then
    return jsonb_build_object('ok', false, 'reason', 'session_limit', 'session_remaining', 0);
  end if;

  select count(*), max(g.created_at) into v_window, v_last
    from public.ai_gift_generations g
   where g.profile_id = v_pid
     and g.created_at > now() - interval '30 days';
  if v_window >= v_window_cap then
    return jsonb_build_object('ok', false, 'reason', 'monthly_limit', 'session_remaining', v_session_cap - v_session);
  end if;

  if v_last is not null and v_last > now() - interval '10 seconds' then
    return jsonb_build_object('ok', false, 'reason', 'cooldown', 'session_remaining', v_session_cap - v_session);
  end if;

  insert into public.ai_gift_generations (profile_id, session_id, consent_version)
  values (v_pid, p_session, p_consent_version)
  returning id into v_id;

  return jsonb_build_object(
    'ok', true,
    'generation_id', v_id,
    'session_remaining', v_session_cap - (v_session + 1),
    'monthly_remaining', v_window_cap - (v_window + 1)
  );
end
$$;

revoke all on function public.claim_ai_gift_generation(uuid, text) from public, anon, authenticated;
grant execute on function public.claim_ai_gift_generation(uuid, text) to authenticated;
