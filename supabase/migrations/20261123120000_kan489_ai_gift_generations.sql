-- KAN-489 (epic KAN-482) — AI gift suggestions: the server-side generation
-- limit and the insert path for unapproved suggestions.
--
-- Spec v0.8 (20 Nov 2026) §03 "Gifts":
--   * "Generate 10 suggestions per request based on user-authored profile
--     content; up to 5 generations per profile-edit session" — and the open
--     decision recommends "a visible counter and sensible rate limiting".
--   * "up to 10 retained AI suggestions" (KAN-485 AI_GIFT_RULE, cap group
--     gifts_ai, which counts PENDING rows as well as approved ones).
--   * "never publish an unapproved suggestion or overwrite user-authored
--     content".
--
-- Design:
--   * public.ai_gift_generations is an APPEND-ONLY claim log, one row per paid
--     model call. One source gives the per-session count (5), the rolling 24 h
--     count (20) and the 10-second cooldown, and it is auditable. A counter row
--     could give only one of those. A retention prune (rows older than 30
--     days) is a follow-up; nothing reads rows older than 24 hours. The rows
--     are personal data (profile_id + timestamp + session id, no content):
--     the service-role SAR export returns them (SEC-117 person-keyed list)
--     and the profiles cascade erases them on account deletion.
--   * public.claim_ai_gift_generation(p_session, p_consent_version) is called
--     BEFORE the model. It locks the caller's profile row (the same row lock
--     save_profile takes), so two concurrent claims are serialised and cannot
--     both pass the count. A suspended account is refused before anything is
--     counted. Refusals come back as {ok:false, reason}; a SQL error
--     propagates and the server action does NOT call the model (fail closed).
--   * Consent record (review fix): each claim row stores the version of the
--     data-sharing note the member accepted before pressing Generate
--     (`consent_version`, sent by the server action only after it has checked
--     the version is the current one). The claim log is therefore also the
--     record that every disclosure to the AI provider followed the note.
--   * public.insert_ai_gift_suggestions(p_items) stores the moderated
--     suggestions. It writes only fixed values for everything except the
--     title and description: category 'gift_ideas', origin 'ai',
--     approved false, visibility 'private', url null, group_label null. It
--     takes at most the free slots (10 minus the AI rows already held,
--     pending or approved) and reports how many did not fit. It never touches
--     a member's own row and never touches profiles.updated_at, so a
--     generation cannot make an open editor "out of date".
--
-- Threat model (what a member can do by calling these directly over PostgREST):
--   * claim_ai_gift_generation is SECURITY DEFINER because the claim log has
--     RLS on and NO policies: members cannot read, write or delete their own
--     claims. The function derives the profile from auth.uid() only and takes
--     nothing but a session id. Calling it directly only spends the caller's
--     own allowance. There is deliberately NO refund function: a member could
--     call it straight after a successful generation and get unlimited paid
--     calls. Provider failures therefore consume a claim (founder note).
--   * Session ids are generated by the browser, so rotating them resets only
--     the per-session count. The rolling cap of 20 per 24 hours (per profile,
--     not per session) is the real bound on paid calls; the 10-second cooldown
--     stops bursts.
--   * insert_ai_gift_suggestions is SECURITY INVOKER: it runs as the member, so
--     owner RLS and the KAN-485 trigger (title 100 / description 250 / the cap
--     of 10) apply. It grants nothing a member cannot already do with a direct
--     insert into their own profile_items rows (SEC-147 stance, same as
--     save_profile). It is NOT the moderation boundary: the server action runs
--     the contact-detail filter, URL rejection and content moderation BEFORE
--     calling it. A member who calls it directly skips those checks, exactly
--     as a direct table write does today, but can only create PRIVATE,
--     UNAPPROVED rows; publishing still needs an approve in save_profile.
--   * Forged AI rows (review fix): a member could otherwise insert
--     `origin='ai', approved=true, visibility='public'` with any text straight
--     over PostgREST and have it shown under "AI suggested" without moderation
--     or approval, or edit the text of an approved AI row. The BEFORE trigger
--     public.enforce_ai_gift_integrity() forces every AI INSERT to
--     approved=false / visibility='private' / url=null, refuses any change of
--     origin to or from 'ai', and refuses edits to an AI row's title,
--     description, url, category or profile. Approving (save_profile
--     `ai_gifts.approve`) only changes approved / visibility, so it still works.
--   * SEC-103 inverted Supabase's default function grant, and CLAUDE.md
--     gotcha #26 explains why revoking from PUBLIC alone is a no-op on
--     Supabase: the two RPCs are revoked from public, anon AND authenticated,
--     then granted EXECUTE to authenticated only; the trigger function is
--     revoked from all three and granted to service_role only (a trigger
--     function needs no EXECUTE grant to fire — same as KAN-485's
--     enforce_profile_item_rules). The claim function's body checks
--     auth.uid() (INV-4). The table has RLS enabled (R4 / INV-5).
--   * search_path is pinned to `public, pg_temp` on both RPCs and to '' on the
--     trigger function (it references no relation).
--
-- Rollback (manual):
--   drop trigger if exists profile_items_ai_integrity on public.profile_items;
--   drop function if exists public.enforce_ai_gift_integrity();
--   drop function if exists public.insert_ai_gift_suggestions(jsonb);
--   drop function if exists public.claim_ai_gift_generation(uuid, text);
--   drop table if exists public.ai_gift_generations;
--
-- Must be run on the lead's dev apply (SQL is not executed by CI or by the
-- build): see docs/ARCHITECTURE.md "KAN-489 dev-apply checks".

-- ============================================================
-- 1. The claim log.
-- ============================================================
create table if not exists public.ai_gift_generations (
  id          uuid primary key default gen_random_uuid(),
  profile_id  uuid not null references public.profiles(id) on delete cascade,
  session_id  uuid not null,
  consent_version text not null check (char_length(consent_version) between 1 and 64),
  created_at  timestamptz not null default now()
);

create index if not exists ai_gift_generations_profile_created_idx
  on public.ai_gift_generations (profile_id, created_at desc);
create index if not exists ai_gift_generations_profile_session_idx
  on public.ai_gift_generations (profile_id, session_id);

alter table public.ai_gift_generations enable row level security;
-- No policies on purpose: only the SECURITY DEFINER claim function and
-- service_role touch this table.
revoke all on table public.ai_gift_generations from public, anon, authenticated;

-- ============================================================
-- 2. claim_ai_gift_generation — one claim per model call.
-- ============================================================
create or replace function public.claim_ai_gift_generation(p_session uuid, p_consent_version text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_pid     uuid;
  v_suspended boolean;
  v_session integer;
  v_daily   integer;
  v_last    timestamptz;
  v_id      uuid;
begin
  if p_session is null then
    raise exception 'A session id is required' using errcode = '22004';
  end if;
  if p_consent_version is null or btrim(p_consent_version) = '' or char_length(p_consent_version) > 64 then
    raise exception 'A consent version is required' using errcode = '22004';
  end if;

  -- The caller's own profile, locked: concurrent claims run one at a time.
  select p.id, coalesce(p.is_suspended, false) into v_pid, v_suspended
    from public.profiles p
   where p.user_id = auth.uid()
     for update;
  if not found then
    raise exception 'Profile not found' using errcode = '42501';
  end if;
  -- A suspended account spends nothing (SEC-57 stance: no new paid work).
  if v_suspended then
    return jsonb_build_object('ok', false, 'reason', 'suspended');
  end if;

  select count(*) into v_session
    from public.ai_gift_generations g
   where g.profile_id = v_pid
     and g.session_id = p_session;
  if v_session >= 5 then
    return jsonb_build_object('ok', false, 'reason', 'session_limit', 'session_remaining', 0);
  end if;

  select count(*), max(g.created_at) into v_daily, v_last
    from public.ai_gift_generations g
   where g.profile_id = v_pid
     and g.created_at > now() - interval '24 hours';
  if v_daily >= 20 then
    return jsonb_build_object('ok', false, 'reason', 'daily_limit', 'session_remaining', 5 - v_session);
  end if;

  if v_last is not null and v_last > now() - interval '10 seconds' then
    return jsonb_build_object('ok', false, 'reason', 'cooldown', 'session_remaining', 5 - v_session);
  end if;

  insert into public.ai_gift_generations (profile_id, session_id, consent_version)
  values (v_pid, p_session, p_consent_version)
  returning id into v_id;

  return jsonb_build_object(
    'ok', true,
    'generation_id', v_id,
    'session_remaining', 5 - (v_session + 1),
    'daily_remaining', 20 - (v_daily + 1)
  );
end
$$;

revoke all on function public.claim_ai_gift_generation(uuid, text) from public, anon, authenticated;
grant execute on function public.claim_ai_gift_generation(uuid, text) to authenticated;

-- ============================================================
-- 3. insert_ai_gift_suggestions — store moderated suggestions, unapproved.
-- ============================================================
create or replace function public.insert_ai_gift_suggestions(p_items jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_pid      uuid;
  v_n        integer;
  v_held     integer;
  v_free     integer;
  v_take     integer;
  v_item     jsonb;
  v_id       uuid;
  v_desc     text;
  v_inserted jsonb := '[]'::jsonb;
begin
  -- ---------- 1. Shape: an array of 1–10 {title, description?} objects ----------
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Invalid suggestions';
  end if;
  v_n := jsonb_array_length(p_items);
  if v_n < 1 or v_n > 10 then
    raise exception 'Invalid suggestions';
  end if;
  for v_item in select e.value from jsonb_array_elements(p_items) as e(value) loop
    if jsonb_typeof(v_item) <> 'object'
       or exists (select 1 from jsonb_object_keys(v_item) as k(key) where k.key not in ('title', 'description'))
       or jsonb_typeof(v_item->'title') is distinct from 'string'
       or btrim(v_item->>'title') = ''
       or (v_item ? 'description' and jsonb_typeof(v_item->'description') not in ('string', 'null')) then
      raise exception 'Invalid suggestions';
    end if;
  end loop;

  -- ---------- 2. The caller's profile, locked like save_profile ----------
  select p.id into v_pid
    from public.profiles p
   where p.user_id = auth.uid()
     for update;
  if not found then
    raise exception 'Profile not found' using errcode = '42501';
  end if;

  -- ---------- 3. Free slots: 10 retained AI suggestions, pending or approved ----------
  select count(*) into v_held
    from public.profile_items i
   where i.profile_id = v_pid
     and i.origin = 'ai'
     and i.category = 'gift_ideas';
  v_free := greatest(0, 10 - v_held);
  v_take := least(v_free, v_n);

  -- ---------- 4. Insert the first v_take items with fixed values ----------
  for v_item in
    select e.value
      from jsonb_array_elements(p_items) with ordinality as e(value, ord)
     order by e.ord
     limit v_take
  loop
    v_desc := nullif(btrim(coalesce(v_item->>'description', '')), '');
    insert into public.profile_items
      (profile_id, category, title, description, url, group_label, origin, approved, visibility)
    values
      (v_pid, 'gift_ideas', v_item->>'title', v_desc, null, null, 'ai', false, 'private')
    returning id into v_id;
    v_inserted := v_inserted || jsonb_build_array(
      jsonb_build_object('id', v_id, 'title', v_item->>'title', 'description', v_desc));
  end loop;

  return jsonb_build_object('inserted', v_inserted, 'dropped_for_cap', v_n - v_take);
end
$$;

revoke all on function public.insert_ai_gift_suggestions(jsonb) from public, anon, authenticated;
grant execute on function public.insert_ai_gift_suggestions(jsonb) to authenticated;

-- ============================================================
-- 4. enforce_ai_gift_integrity — AI rows cannot be forged or edited.
-- ============================================================
create or replace function public.enforce_ai_gift_integrity()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'INSERT' then
    -- Whoever inserts it, an AI row starts unapproved, private and link-free.
    if new.origin = 'ai' then
      new.approved   := false;
      new.visibility := 'private';
      new.url        := null;
    end if;
    return new;
  end if;

  if new.origin is distinct from old.origin and (old.origin = 'ai' or new.origin = 'ai') then
    raise exception 'An AI suggestion cannot become a member entry, or the reverse' using errcode = '42501';
  end if;
  if old.origin = 'ai' and (
       new.title       is distinct from old.title
    or new.description is distinct from old.description
    or new.url         is distinct from old.url
    or new.category    is distinct from old.category
    or new.profile_id  is distinct from old.profile_id
  ) then
    raise exception 'An AI suggestion cannot be edited' using errcode = '42501';
  end if;
  return new;
end$$;

revoke all on function public.enforce_ai_gift_integrity() from public, anon, authenticated;
grant execute on function public.enforce_ai_gift_integrity() to service_role;

drop trigger if exists profile_items_ai_integrity on public.profile_items;
create trigger profile_items_ai_integrity before insert or update on public.profile_items
  for each row execute function public.enforce_ai_gift_integrity();
